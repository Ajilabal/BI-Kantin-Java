    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        try {
        Connection c = Koneksi.configDB();
        Statement s = c.createStatement();

        String sql = "SELECT * FROM users WHERE username='" + txtUsername.getText() + "' AND password='" + txtPassword.getText() + "'";
        ResultSet r = s.executeQuery(sql);

        if (r.next()) {
            String role = r.getString("role");
            int idUser = r.getInt("id"); // Mengambil ID user yang sedang login

            if (role.equalsIgnoreCase("admin")) {
                JOptionPane.showMessageDialog(this, "Login Berhasil sebagai Admin!");
                new FormAdmin().setVisible(true);
                this.dispose();
            } else if (role.equalsIgnoreCase("siswa")) {
                JOptionPane.showMessageDialog(this, "Login Berhasil sebagai Siswa!");
                // Mengirim idUser ke FormSiswa agar datanya dinamis
                new FormSiswa(idUser).setVisible(true);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Role tidak dikenali!");
            }
        } else {
            JOptionPane.showMessageDialog(this, "Username atau Password salah!");
            txtPassword.setText("");
        }
        } catch (HeadlessException | SQLException e) {
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + e.getMessage());
        }
    }//GEN-LAST:event_btnLoginActionPerformed

