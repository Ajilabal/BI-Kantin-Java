    public void loadDataPendaftar() {
        model = new DefaultTableModel();
        model.addColumn("ID Transaksi");
        model.addColumn("Nama Siswa");
        model.addColumn("Tanggal");
        model.addColumn("Total Harga");
        model.addColumn("Status Pesanan");
        tblPendaftar.setModel(model);
        
        try{
            Connection c = Koneksi.configDB();
            Statement s = c.createStatement();
            // Query yang benar disesuaikan dengan relasi tabel transaksi dan users
            String sql = "SELECT transaksi.id_transaksi, users.nama_lengkap, transaksi.tgl_transaksi, transaksi.total_harga, transaksi.status_transaksi "
                       + "FROM transaksi "
                       + "JOIN users ON transaksi.id_siswa = users.id "
                       + "ORDER BY transaksi.id_transaksi DESC";
            ResultSet r = s.executeQuery(sql);
            while (r.next()){
                model.addRow(new Object[]{
                    r.getString("id_transaksi"),
                    r.getString("nama_lengkap"),
                    r.getString("tgl_transaksi"),
                    "Rp " + r.getString("total_harga"),
                    r.getString("status_transaksi")
                });
            }
        }catch (Exception e){
            JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage());
        }
    }
