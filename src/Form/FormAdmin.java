    private void btnUbahStatusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahStatusActionPerformed
        int baris = tblPendaftar.getSelectedRow();
        if (baris == -1) {
            JOptionPane.showMessageDialog(this, "Pilih data transaksi di tabel terlebih dahulu!");
            return;
        }
        String idTransaksi = model.getValueAt(baris, 0).toString();
        String statusBaru = JOptionPane.showInputDialog(this, "Masukkan Status Baru (Contoh: Menunggu Konfirmasi, Sedang Dimasak, Siap Diambil, Selesai, Pending, Diproses):");

        if (statusBaru != null && !statusBaru.trim().isEmpty()) {
            try {
                Connection c = Koneksi.configDB();
                Statement s = c.createStatement();
                // Query update status pesanan pada tabel transaksi
                String sql = "UPDATE transaksi SET status_transaksi = '" + statusBaru + "' WHERE id_transaksi = '" + idTransaksi + "'";
                s.executeUpdate(sql);
                JOptionPane.showMessageDialog(this, "Status pesanan berhasil diperbarui!");
                loadDataPendaftar();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal update status: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnUbahStatusActionPerformed

