    public void tampilKategori() {
        try {
            String sql = "SELECT * FROM kategori_menu";
            java.sql.Connection conn = Koneksi.configDB();
            java.sql.Statement stm = conn.createStatement();
            java.sql.ResultSet res = stm.executeQuery(sql);

            cbKategori.removeAllItems();
            cbKategori.addItem("- Pilih Kategori -");

            while (res.next()) {
                cbKategori.addItem(res.getString("nama_kategori"));
            }
        } catch (SQLException e) {
            System.out.println("Gagal memuat kategori: " + e.getMessage());
        }
    }
    
    public void tampilTracking() {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
        model.addColumn("ID Transaksi");
        model.addColumn("Tanggal");
        model.addColumn("Total Bayar");
        model.addColumn("Status Pesanan");

        try {
            String sql = "SELECT id_transaksi, tgl_transaksi, total_harga, status_transaksi "
                       + "FROM transaksi WHERE id_siswa = '" + idSiswaLogin + "' ORDER BY id_transaksi DESC";

            java.sql.Connection conn = Koneksi.configDB();
            java.sql.Statement stm = conn.createStatement();
            java.sql.ResultSet res = stm.executeQuery(sql);

            while (res.next()) {
                model.addRow(new Object[]{
                    res.getString("id_transaksi"),
                    res.getString("tgl_transaksi"),
                    "Rp " + res.getString("total_harga"),
                    res.getString("status_transaksi")
                });
            }

            tblTracking.setModel(model);

        } catch (SQLException e) {
            System.out.println("Gagal memuat tracking status: " + e.getMessage());
        }
    }
    
