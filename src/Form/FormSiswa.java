    private void btnDaftarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDaftarActionPerformed
        try {
            String menuDipilih = cbMenu.getSelectedItem().toString();
            String jumlahBeli = txtJumlah.getText();
            String hargaMenu = txtHarga.getText();
            
            if(menuDipilih.equals("- Pilih Menu -") || jumlahBeli.equals("")) {
                javax.swing.JOptionPane.showMessageDialog(this, "Pilih menu dan isi jumlah beli terlebih dahulu!");
                return;
            }

            int harga = Integer.parseInt(hargaMenu);
            int jumlah = Integer.parseInt(jumlahBeli);
            int subtotal = harga * jumlah;

            String sqlGetMenu = "SELECT id_menu FROM menu WHERE nama_menu = '" + menuDipilih + "'";
            java.sql.Connection conn = Koneksi.configDB();
            java.sql.Statement stm = conn.createStatement();
            java.sql.ResultSet resMenu = stm.executeQuery(sqlGetMenu);
            
            if (resMenu.next()) {
                int idMenu = resMenu.getInt("id_menu");
                
                String sqlTransaksi = "INSERT INTO transaksi (id_siswa, id_pembayaran, total_harga, status_transaksi) "
                                    + "VALUES ('" + idSiswaLogin + "', 1, '" + subtotal + "', 'Pending')";
                stm.executeUpdate(sqlTransaksi, java.sql.Statement.RETURN_GENERATED_KEYS);
                
                java.sql.ResultSet resKey = stm.getGeneratedKeys();
                if (resKey.next()) {
                    int idTransaksiBaru = resKey.getInt(1);
                    
                    String sqlDetail = "INSERT INTO detail_transaksi (id_transaksi, id_menu, jumlah, subtotal) "
                                     + "VALUES ('" + idTransaksiBaru + "', '" + idMenu + "', '" + jumlah + "', '" + subtotal + "')";
                    stm.executeUpdate(sqlDetail);
                    
                    String sqlUpdateStok = "UPDATE menu SET stok = stok - " + jumlah + " WHERE id_menu = '" + idMenu + "'";
                    stm.executeUpdate(sqlUpdateStok);
                    
                    javax.swing.JOptionPane.showMessageDialog(this, "Pesanan Berhasil Dibuat! Total: Rp " + subtotal);
                    
                    txtJumlah.setText("");
                    tampilTracking();
                }
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal Memproses Pesanan: " + e.getMessage());
        }
    }//GEN-LAST:event_btnDaftarActionPerformed

