    private void cbKategoriActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cbKategoriActionPerformed
        try {
            if (cbKategori.getSelectedItem() != null) {
                String kategoriDipilih = cbKategori.getSelectedItem().toString();
                if (!kategoriDipilih.equals("- Pilih Kategori -")) {
                    String sql = "SELECT menu.nama_menu FROM menu "
                               + "JOIN kategori_menu ON menu.id_kategori = kategori_menu.id_kategori "
                               + "WHERE kategori_menu.nama_kategori = '" + kategoriDipilih + "'";
                    
                    java.sql.Connection conn = Koneksi.configDB();
                    java.sql.Statement stm = conn.createStatement();
                    java.sql.ResultSet res = stm.executeQuery(sql);
                    
                    cbMenu.removeAllItems();
                    cbMenu.addItem("- Pilih Menu -");
                    
                    while (res.next()) {
                        cbMenu.addItem(res.getString("nama_menu"));
                    }
                }
            }
        } catch (Exception e) {
            System.out.println("Gagal memuat menu: " + e.getMessage());
        }
    }//GEN-LAST:event_cbKategoriActionPerformed

